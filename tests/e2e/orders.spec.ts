import { test, expect } from '@playwright/test';
import { login } from './helpers';
for(const width of [1280,390])test(`crea, asigna, comenta y entrega en las tres vistas a ${width}px`,async({page})=>{
  await page.setViewportSize({width,height:850});
  const title=`Banner para ecommerce ${width}`;
  test.setTimeout(90000);
  await login(page,'joel.yc23@gmail.com');
  await page.getByRole('button',{name:'Configurar equipo y marca'}).click();
  const setup=page.getByRole('dialog',{name:'Configurar equipo y marca'});
  await setup.getByLabel('Nombre del equipo',{exact:true}).fill(`Equipo navegador ${width}`);
  await setup.getByLabel('ID del equipo',{exact:true}).fill(`browser-team-${width}`);
  await setup.getByLabel('Nombre completo de marca').fill('Converse');
  await setup.getByLabel('ID de marca',{exact:true}).fill('converse');
  await setup.getByRole('button',{name:'Crear combinación'}).click();
  await expect(setup).toBeHidden();
  await page.getByRole('button',{name:'Nuevo pedido'}).click();
  const create=page.getByRole('dialog',{name:'Nuevo pedido'});
  await create.getByLabel('Título',{exact:true}).fill(title);
  await create.getByLabel('Marca',{exact:true}).selectOption({label:'Converse'});
  await create.getByLabel('Equipo',{exact:true}).selectOption({label:`Equipo navegador ${width}`});
  await create.getByRole('button',{name:'Crear pedido',exact:true}).click();
  const detail=page.getByRole('dialog',{name:title});
  await expect(detail).toBeVisible();
  await detail.getByRole('button',{name:'Cerrar detalle'}).focus();
  await page.keyboard.press('Tab');
  await expect(detail.getByLabel('Título',{exact:true})).toBeFocused();
  await detail.getByLabel('Deadline · hora de Lima').fill(`${new Date().toISOString().slice(0,7)}-15T17:00`);
  await detail.getByLabel('Descripción / brief').fill('Respetar la identidad visual.');
  await detail.getByLabel('Responsable principal').selectOption({label:'Identidad de prueba'});
  await detail.getByRole('button',{name:'Guardar detalles'}).click();
  await expect(detail.locator('.event-list li').filter({hasText:'Detalles actualizados'})).toBeVisible();
  await detail.getByRole('button',{name:'Añadir pieza'}).click();
  const piece=detail.locator('.piece-editor');
  await piece.getByLabel('Nombre',{exact:true}).fill('Banner principal');
  await piece.getByLabel('Estado de pieza').selectOption('Lista');
  await piece.getByRole('button',{name:'Guardar pieza'}).click();
  await expect(piece).toBeHidden();
  await expect(detail.getByText('1 de 1 piezas listas',{exact:true})).toBeVisible();
  await detail.getByLabel('Comentario',{exact:true}).fill('Listo para revisión.');
  await detail.getByRole('button',{name:'Publicar comentario'}).click();
  await expect(detail.getByText('Listo para revisión.',{exact:true})).toBeVisible();
  await detail.getByLabel('Enlace completo').fill('https://mega.nz/file/browser-test#FULL-fragment');
  await detail.getByRole('button',{name:'Registrar entrega',exact:true}).click();
  await expect(detail.getByRole('link',{name:'Abrir entrega · Pedido completo'})).toHaveAttribute('href','https://mega.nz/file/browser-test#FULL-fragment');
  await detail.getByRole('button',{name:'Marcar Entregado',exact:true}).click();
  await expect(detail.getByText(`Equipo navegador ${width} · Converse · Entregado`,{exact:true})).toBeVisible();
  await detail.getByRole('button',{name:'Cerrar detalle'}).click();
  await page.getByRole('button',{name:'Mis pedidos',exact:true}).click();
  await expect(page.getByRole('button',{name:title,exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Lista',exact:true}).click();
  await expect(page.getByRole('button',{name:title,exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Calendario',exact:true}).click();
  await expect(page.getByRole('button',{name:`Converse · ${title}`,exact:true})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.reload();
  await page.getByRole('button',{name:title,exact:true}).click();
  await expect(page.getByText('Listo para revisión.',{exact:true})).toBeVisible();
});
